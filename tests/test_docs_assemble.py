OLD = {"HANDOFF.md": HANDOFF_OLD, "docs/TRACEABILITY.md": TRACE_OLD, "docs/BACKLOG.md": BACKLOG_OLD}


def write_old(root: Path) -> None:
    for rel, text in OLD.items():
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(text, encoding="utf-8")


def migrated(root: Path) -> Path:
    write_old(root)
    assert da.main(["--root", str(root), "migrate"]) == 0
    return root


def read(root: Path, rel: str) -> str:
    return (root / rel).read_text(encoding="utf-8")


@pytest.fixture
def git_env(monkeypatch):
    for k, v in {"GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@example.invalid", "GIT_COMMITTER_NAME": "t",
                 "GIT_COMMITTER_EMAIL": "t@example.invalid", "GIT_CONFIG_GLOBAL": os.devnull,
                 "GIT_CONFIG_NOSYSTEM": "1"}.items():
        monkeypatch.setenv(k, v)


def git(root: Path, *args: str) -> str:
    return subprocess.run(["git", *args], cwd=root, check=True, capture_output=True, text=True).stdout


def commit_all(root: Path, msg: str) -> None:
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", msg)


def old_repo(root: Path) -> Path:
    git(root, "init", "-q", "-b", "main")
    write_old(root)
    commit_all(root, "old docs")
    return root


# ------------------------------------------------------------------------------------------------- rendering

def test_migrating_the_old_docs_and_rendering_them_reproduces_them_exactly(tmp_path):
    root = migrated(tmp_path)
    for rel, text in OLD.items():
        assert da.strip_notice(read(root, rel)) == text
        assert read(root, rel).startswith("<!-- Generated by scripts/docs_assemble.py")
    assert sorted(p.name for p in (root / "docs/traceability.d").iterdir()) == [
        "D1.yaml", "R1.yaml", "R2.yaml", "_template.md"]


def test_rendering_is_deterministic_whatever_order_the_fragments_are_listed_in(tmp_path):
    root = migrated(tmp_path)
    da.cmd_new_handoff(root, "b-change", "status")
    da.cmd_new_handoff(root, "a-change", "status")
    for p in (root / "docs/handoff.d").glob("2*.md"):
        p.write_text(f"- {p.stem}.\n", encoding="utf-8")

    fs = da.FsTree(root)

    class Reversed:
        def read(self, rel: str) -> str | None:
            return fs.read(rel)

        def names(self, rel_dir: str) -> list[str]:
            return list(reversed(fs.names(rel_dir)))

    assert da.build(fs) == da.build(Reversed()) == da.build(fs)


def test_handoff_fragments_render_newest_first_at_the_top_of_their_section(tmp_path):
    root = migrated(tmp_path)
    d = root / "docs/handoff.d"
    (d / "2026-10-09-older.md").write_text("- Older change.\n", encoding="utf-8")
    (d / "2026-10-11-newer.md").write_text("- Newer change.\n  Second line.\n", encoding="utf-8")
    (d / "2026-10-10-step.md").write_text("---\nsection: next\n---\n- A next step.\n", encoding="utf-8")
    text = da.build(da.FsTree(root))["HANDOFF.md"]
    assert ("## Where things are (as of 2026-10-05)\n- Newer change.\n  Second line.\n- Older change.\n- Built A.\n"
            in text)
    assert "## Next steps (no owner input needed unless marked)\n- A next step.\n- Do C.\n" in text


def test_a_handoff_fragment_with_a_bad_name_or_an_unwritten_stub_is_refused(tmp_path):
    root = migrated(tmp_path)
    (root / "docs/handoff.d/Notes.md").write_text("- x\n", encoding="utf-8")
    da.cmd_new_handoff(root, "stub", "status")
    with pytest.raises(da.DocsError) as exc:
        da.build(da.FsTree(root))
    assert "Notes.md: name must be" in str(exc.value)
    assert "stub.md: the body must be" in str(exc.value)


def test_the_counts_table_is_computed_from_the_row_statuses(tmp_path):
    root = migrated(tmp_path)
    (root / "docs/traceability.d/R1.yaml").write_text(
        "id: R1\nrequirement: r\nstatus: in review (P1)\ncode: c\ntest: t\n", encoding="utf-8")
    da.cmd_new_row(root, "D", "new", {"requirement": "q", "status": "deviates", "code": "c", "test": "t"})
    text = da.build(da.FsTree(root))["docs/TRACEABILITY.md"]
    assert ("| implemented | 1 |\n| partial | 0 |\n| missing | 1 |\n| deviates | 1 |\n| in review | 1 |\n"
            "| **total** | **4** |\n") in text
    assert "| D2 | q | deviates | c | t |" in text


def test_a_row_with_an_unknown_status_or_an_empty_cell_is_refused(tmp_path):
    root = migrated(tmp_path)
    (root / "docs/traceability.d/R1.yaml").write_text(
        "id: R1\nrequirement: r\nstatus: done\ncode: c\ntest: t\n", encoding="utf-8")
    da.cmd_new_row(root, "R", "blank")
    with pytest.raises(da.DocsError) as exc:
        da.build(da.FsTree(root))
    assert "R1.yaml: status must start with one of" in str(exc.value)
    assert "R3-blank.yaml: fill in requirement, status, code, test" in str(exc.value)


def test_legacy_rows_keep_their_position_and_new_rows_sort_by_number(tmp_path):
    root = migrated(tmp_path)
    assert "order: 0.5" in read(root, "docs/traceability.d/R2.yaml")
    da.cmd_new_row(root, "R", "new", {"requirement": "n", "status": "missing", "code": "c", "test": "t"})
    text = da.build(da.FsTree(root))["docs/TRACEABILITY.md"]
    assert text.index("| R2 |") < text.index("| R1 |") < text.index("| R3 |")


# ------------------------------------------------------------------------------------------------- ids

def test_new_row_takes_the_next_free_id_for_its_prefix_and_refuses_an_unknown_prefix(tmp_path):
    root = migrated(tmp_path)
    assert da.cmd_new_row(root, "R", "x").name == "R3-x.yaml"
    assert da.cmd_new_row(root, "D", "y").name == "D2-y.yaml"
    with pytest.raises(da.DocsError, match="no table for prefix Q"):
        da.cmd_new_row(root, "Q", "z")


def test_new_item_takes_the_next_number_and_ranks_last(tmp_path):
    root = migrated(tmp_path)
    path = da.cmd_new_item(root, "five", "Five", stage="RUN", size="S")
    assert path.name == "05-five.md"
    path.write_text(path.read_text(encoding="utf-8").replace(da.STUB, "written"), encoding="utf-8")
    text = da.build(da.FsTree(root))["docs/BACKLOG.md"]
    assert "| 1 | One | FIND | M | done |\n| 5 | Five | RUN | S | proposed |\n" in text
    assert "- **3. Three.** Value: three.\n- **5. Five.** Value: written. Acceptance: written.\n" in text


def test_two_fragments_with_the_same_id_fail_the_check_with_the_fix_ids_hint(tmp_path, capsys):
    root = migrated(tmp_path)
    for slug in ("lane-a", "lane-b"):
        da.cmd_new_row(root, "R", slug, {"requirement": slug, "status": "missing", "code": "c", "test": "t"})
    (root / "docs/traceability.d/R4-lane-b.yaml").rename(root / "docs/traceability.d/R3-lane-b.yaml")
    (root / "docs/traceability.d/R3-lane-b.yaml").write_text(
        "id: R3\nrequirement: lane-b\nstatus: missing\ncode: c\ntest: t\n", encoding="utf-8")
    assert da.main(["--root", str(root), "check"]) == 1
    err = capsys.readouterr().err
    assert "id R3 is used by R3-lane-a.yaml, R3-lane-b.yaml" in err
    assert "docs_assemble.py fix-ids" in err


def test_fix_ids_keeps_the_id_for_the_row_that_landed_first_and_renumbers_the_other(tmp_path, git_env):
    root = old_repo(tmp_path)
    assert da.main(["--root", str(root), "migrate"]) == 0
    da.cmd_new_row(root, "R", "landed", {"requirement": "first", "status": "missing", "code": "c", "test": "t"})
    commit_all(root, "migrate + R3")
    (root / "docs/traceability.d/R3-late.yaml").write_text(
        "id: R3\nrequirement: second\nstatus: missing\ncode: c\ntest: t\n", encoding="utf-8")
    assert da.main(["--root", str(root), "fix-ids"]) == 0
    assert not (root / "docs/traceability.d/R3-late.yaml").exists()
    assert "requirement: second" in read(root, "docs/traceability.d/R4-late.yaml")
    assert "id: R4" in read(root, "docs/traceability.d/R4-late.yaml")
    assert "requirement: first" in read(root, "docs/traceability.d/R3-landed.yaml")
    assert da.main(["--root", str(root), "check"]) == 0


