def test_check_fails_with_a_hint_when_a_rendered_file_was_edited_by_hand(tmp_path, capsys):
    root = migrated(tmp_path)
    assert da.main(["--root", str(root), "check"]) == 0
    (root / "HANDOFF.md").write_text(read(root, "HANDOFF.md") + "- Hand edit.\n", encoding="utf-8")
    assert da.main(["--root", str(root), "check"]) == 1
    err = capsys.readouterr().err
    assert "HANDOFF.md differs from its fragments" in err
    assert "python scripts/docs_assemble.py" in err
    assert "+- Hand edit." in err


def test_the_committed_rendered_files_match_their_fragments():
    assert set(da.build(da.FsTree(ROOT))) == set(da.RENDERED)  # all three docs are generated
    assert da.main(["--root", str(ROOT), "check"]) == 0


def test_parsing_the_committed_rendered_docs_round_trips_losslessly():
    tree = da.FsTree(ROOT)
    for spec in da.SPECS.values():
        text = da.strip_notice(tree.read(spec.rendered) or "")
        template, recs = spec.parse(text)
        assert spec.render(template, recs) == text, spec.rendered
    handoff = da.strip_notice(tree.read("HANDOFF.md") or "")
    assert da.render_handoff(da.handoff_skeleton(handoff), []) == handoff


def test_the_migration_commit_was_lossless_against_the_docs_it_replaced(tmp_path):
    """Replays the one-off migration on the pre-migration files (skipped in a shallow clone)."""
    added = subprocess.run(["git", "log", "--diff-filter=A", "--format=%H", "--", "docs/traceability.d/_template.md"],
                           cwd=ROOT, capture_output=True, text=True)
    shas = added.stdout.split()
    if added.returncode != 0 or not shas:
        pytest.skip("migration commit not in this checkout's history")
    parent = f"{shas[-1]}^"
    before: dict[str, str] = {}
    for rel in OLD:
        shown = subprocess.run(["git", "show", f"{parent}:{rel}"], cwd=ROOT, capture_output=True, text=True)
        if shown.returncode != 0:
            pytest.skip("pre-migration files not available (shallow clone)")
        before[rel] = shown.stdout
        (tmp_path / rel).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / rel).write_text(shown.stdout, encoding="utf-8")
    assert da.main(["--root", str(tmp_path), "migrate"]) == 0
    for rel, text in before.items():
        assert da.strip_notice(read(tmp_path, rel)) == text, rel


# ------------------------------------------------------------------------------------------------- absorb / merge

def old_style_branch(root: Path) -> None:
    """A lane forked before the migration that edits the rendered files the old way."""
    git(root, "checkout", "-q", "-b", "lane-old")
    (root / "HANDOFF.md").write_text(
        HANDOFF_OLD.replace("- Built B.\n", "- Built B.\n- Lane change (2026-10-11).\n  Detail.\n")
                   .replace("Intro.", "Intro, edited.")
                   .replace("1. Numbered.\n", "1. Numbered.\n- Lane next step.\n"), encoding="utf-8")
    (root / "docs/TRACEABILITY.md").write_text(
        TRACE_OLD.replace("| R1 | \"risk\" | partial |", "| R1 | \"risk\" | implemented |")
                 .replace("| D1 |", "| D2 | \"lane row\" | implemented | lane.py | t3 |\n| D1 |")
                 .replace("| implemented | 1 |", "| implemented | 3 |"), encoding="utf-8")
    (root / "docs/BACKLOG.md").write_text(
        BACKLOG_OLD.replace("| 1 | One | FIND | M | done |\n", "| 5 | Lane item | RUN | S | ready |\n"
                                                             "| 1 | One | FIND | M | done |\n")
                   .replace("- **3. Three.** Value: three.\n", "- **3. Three.** Value: three.\n"
                                                             "- **5. Lane item.** Value: five.\n"), encoding="utf-8")
    commit_all(root, "lane work, old style")
    git(root, "checkout", "-q", "main")


def test_absorb_turns_an_old_style_branch_into_fragments_and_renumbers_a_taken_id(tmp_path, git_env):
    root = old_repo(tmp_path)
    old_style_branch(root)
    assert da.main(["--root", str(root), "migrate"]) == 0
    da.cmd_new_row(root, "D", "main", {"requirement": "main row", "status": "missing", "code": "c", "test": "t"})
    commit_all(root, "migrate, and main takes D2")
    res = da.cmd_absorb(root, "lane-old")
    assert res.conflicts == []
    assert any("new D2 is taken; absorbed as D3" in n for n in res.notes)
    da.cmd_render(root)
    handoff = read(root, "HANDOFF.md")
    assert "Intro, edited." in handoff  # an edit of static text lands in the template
    assert "## Where things are (as of 2026-10-05)\n- Lane change (2026-10-11).\n  Detail.\n- Built A." in handoff
    assert "## Next steps (no owner input needed unless marked)\n- Lane next step.\n- Do C." in handoff
    trace = read(root, "docs/TRACEABILITY.md")
    assert '| R1 | "risk" | implemented | gate.py | t1 |' in trace
    assert '| D2 | main row | missing | c | t |' in trace
    assert '| D3 | "lane row" | implemented | lane.py | t3 |' in trace
    assert "| **total** | **5** |" in trace
    backlog = read(root, "docs/BACKLOG.md")
    assert "| 2 | Two | RUN | S | ready |\n| 5 | Lane item | RUN | S | ready |\n| 1 | One" in backlog
    assert "- **5. Lane item.** Value: five.\n" in backlog
    assert da.main(["--root", str(root), "check"]) == 0


def test_merge_absorbs_an_old_style_branch_in_one_command(tmp_path, git_env):
    root = old_repo(tmp_path)
    old_style_branch(root)
    assert da.main(["--root", str(root), "migrate"]) == 0
    commit_all(root, "migrate")
    assert da.main(["--root", str(root), "merge", "lane-old"]) == 0
    assert git(root, "status", "--porcelain") == ""
    assert len(git(root, "log", "-1", "--format=%P").split()) == 2  # a real merge commit
    assert da.main(["--root", str(root), "check"]) == 0
    assert "- Lane change (2026-10-11)." in read(root, "HANDOFF.md")
    assert '| D2 | "lane row" | implemented | lane.py | t3 |' in read(root, "docs/TRACEABILITY.md")


def test_merging_two_new_style_branches_that_took_the_same_id_renumbers_the_second(tmp_path, git_env):
    root = old_repo(tmp_path)
    assert da.main(["--root", str(root), "migrate"]) == 0
    commit_all(root, "migrate")
    for lane in ("lane-a", "lane-b"):
        git(root, "checkout", "-q", "-b", lane, "main")
        da.cmd_new_row(root, "R", lane, {"requirement": lane, "status": "missing", "code": "c", "test": "t"})
        frag = da.cmd_new_handoff(root, lane, "status")
        frag.write_text(f"- {lane} done.\n", encoding="utf-8")
        da.cmd_render(root)
        commit_all(root, lane)
    git(root, "checkout", "-q", "main")
    assert da.main(["--root", str(root), "merge", "lane-a"]) == 0
    assert da.main(["--root", str(root), "merge", "lane-b"]) == 0
    trace = read(root, "docs/TRACEABILITY.md")
    assert "| R3 | lane-a |" in trace and "| R4 | lane-b |" in trace
    handoff = read(root, "HANDOFF.md")
    assert "- lane-a done." in handoff and "- lane-b done." in handoff
    assert da.main(["--root", str(root), "check"]) == 0
    assert git(root, "status", "--porcelain") == ""


def test_merge_refuses_a_new_style_branch_that_edited_a_rendered_file_by_hand(tmp_path, git_env):
    root = old_repo(tmp_path)
    assert da.main(["--root", str(root), "migrate"]) == 0
    commit_all(root, "migrate")
    git(root, "checkout", "-q", "-b", "lane-hand")
    (root / "HANDOFF.md").write_text(read(root, "HANDOFF.md") + "- Hand edit.\n", encoding="utf-8")
    commit_all(root, "hand edit")
    git(root, "checkout", "-q", "main")
    assert da.main(["--root", str(root), "merge", "lane-hand"]) == 1
    assert "MERGE_HEAD" not in os.listdir(root / ".git")  # refused before merging anything
    assert len(git(root, "log", "-1", "--format=%P").split()) == 1
