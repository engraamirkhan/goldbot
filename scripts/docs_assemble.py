# ---------------------------------------------------------------------------------------------------------- trees

class Tree(Protocol):
    def read(self, rel: str) -> str | None: ...
    def names(self, rel_dir: str) -> list[str]: ...


@dataclass(frozen=True)
class FsTree:
    root: Path

    def read(self, rel: str) -> str | None:
        p = self.root / rel
        return p.read_text(encoding="utf-8") if p.is_file() else None

    def names(self, rel_dir: str) -> list[str]:
        d = self.root / rel_dir
        return sorted(p.name for p in d.iterdir() if p.is_file()) if d.is_dir() else []


@dataclass(frozen=True)
class GitTree:
    root: Path
    ref: str

    def read(self, rel: str) -> str | None:
        r = git(self.root, "show", f"{self.ref}:{rel}", check=False)
        return r.stdout if r.returncode == 0 else None

    def names(self, rel_dir: str) -> list[str]:
        r = git(self.root, "ls-tree", "--name-only", self.ref, f"{rel_dir}/", check=False)
        return sorted(Path(line).name for line in r.stdout.splitlines() if line)


def git(root: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    r = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, encoding="utf-8")
    if check and r.returncode != 0:
        raise DocsError(f"git {' '.join(args)} failed: {r.stderr.strip()}")
    return r


# ------------------------------------------------------------------------------------------------- shared helpers

def lines_of(text: str) -> list[str]:
    return text.split("\n")[:-1] if text.endswith("\n") else text.split("\n")


def strip_notice(text: str) -> str:
    first, _, rest = text.partition("\n")
    return rest if first.startswith("<!-- Generated by scripts/docs_assemble.py") else text


def with_notice(src: str, body: str) -> str:
    return NOTICE.format(src=src) + "\n" + body


def split_front_matter(text: str) -> tuple[dict[str, Any], str]:
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 3)
    if end < 0:
        if text.endswith("\n---"):
            end = len(text) - 4
        else:
            raise DocsError("front matter opened with --- but never closed")
    data = yaml.safe_load(text[4:end + 1]) or {}
    if not isinstance(data, dict):
        raise DocsError("front matter is not a mapping")
    return data, text[end + 5:]


def dump_yaml(data: dict[str, Any]) -> str:
    return yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=10**6)


def slugify(text: str, words: int = 6) -> str:
    text = re.sub(r"[`*_()\[\]]", "", text.lower())
    parts = [p for p in re.split(r"[^a-z0-9]+", text) if p][:words]
    return "-".join(parts)[:48].strip("-") or "item"


def natural_order(seq: list[tuple[str, float]]) -> dict[str, float]:
    """Explicit `order` values only where the appearance order is not the natural (numeric) one."""
    out: dict[str, float] = {}
    for (key, num), (_, nxt) in zip(seq, seq[1:], strict=False):
        if num > nxt:
            out[key] = nxt - 0.5
    return out


# ---------------------------------------------------------------------------------------------------- the handoff

HANDOFF_DIR = "docs/handoff.d"
HANDOFF_SECTIONS = {"status": "## Where things are", "next": "## Next steps"}
HANDOFF_NAME = re.compile(r"^(\d{4}-\d{2}-\d{2})-([a-z0-9][a-z0-9-]*)\.md$")


@dataclass(frozen=True)
class Fragment:
    name: str
    date: str
    section: str
    body: str


def load_handoff(tree: Tree, errors: list[str]) -> list[Fragment]:
    out = []
    for name in tree.names(HANDOFF_DIR):
        if name in (TEMPLATE, "README.md"):
            continue
        m = HANDOFF_NAME.match(name)
        if not m:
            errors.append(f"{HANDOFF_DIR}/{name}: name must be <YYYY-MM-DD>-<slug>.md (lower-case slug)")
            continue
        try:
            meta, body = split_front_matter(tree.read(f"{HANDOFF_DIR}/{name}") or "")
        except DocsError as exc:
            errors.append(f"{HANDOFF_DIR}/{name}: {exc}")
            continue
        section = str(meta.get("section", "status"))
        body = body.strip("\n")
        if section not in HANDOFF_SECTIONS or set(meta) - {"section"}:
            errors.append(f"{HANDOFF_DIR}/{name}: front matter may only hold `section: status|next`")
        elif not body.startswith("- ") or STUB in body:
            errors.append(f"{HANDOFF_DIR}/{name}: the body must be one or more markdown bullets starting with '- '")
        else:
            out.append(Fragment(name, m.group(1), section, body))
    return out


def render_handoff(template: str, frags: list[Fragment]) -> str:
    ordered = sorted(sorted(frags, key=lambda f: f.name), key=lambda f: f.date, reverse=True)
    out = []
    for line in lines_of(template):
        m = re.fullmatch(r"<!-- handoff\.d:(\w+) -->", line)
        if m:
            out += [f.body for f in ordered if f.section == m.group(1)]
        else:
            out.append(line)
    return "\n".join(out) + "\n"


def handoff_skeleton(text: str) -> str:
    """The template form of an old-style HANDOFF.md: a marker after each section heading."""
    out, seen = [], set()
    for line in lines_of(strip_notice(text)):
        out.append(line)
        for section, heading in HANDOFF_SECTIONS.items():
            if line.startswith(heading) and section not in seen:
                out.append(f"<!-- handoff.d:{section} -->")
                seen.add(section)
    missing = set(HANDOFF_SECTIONS) - seen
    if missing:
        raise DocsError(f"HANDOFF.md has no {', '.join(HANDOFF_SECTIONS[s] for s in sorted(missing))} heading")
    return "\n".join(out) + "\n"


# ----------------------------------------------------------------------------------------------- structured docs

@dataclass
class Rec:
    """One TRACEABILITY row or BACKLOG item: `key` is the id ("R12", "28"); `name` the file it lives in."""

    key: str
    data: dict[str, Any]
    name: str | None = None


@dataclass
class Spec:
    kind: str
    rendered: str
    dir: str
    merge_fields: tuple[str, ...]
    load: Callable[[Tree, list[str]], list[Rec]]
    render: Callable[[str, list[Rec]], str]
    parse: Callable[[str], tuple[str, list[Rec]]]
    file_text: Callable[[Rec], str]
    file_name: Callable[[Rec, str], str]
    renumber: Callable[[Rec, str], Rec]


# ---- TRACEABILITY

TRACE_DIR = "docs/traceability.d"
TRACE_ID = re.compile(r"^([A-Z]+)(\d+)$")
TRACE_ROW = re.compile(r"^\| ([A-Z]+\d+) \| (.*) \|$")
TRACE_FIELDS = ("requirement", "status", "code", "test")
STATUSES = ("implemented", "partial", "missing", "deviates", "in review")


def prefix_of(key: str) -> str:
    m = TRACE_ID.match(key)
    return m.group(1) if m else ""


def status_of(status: str) -> str | None:
    for s in STATUSES:
        if status == s or (status.startswith(s) and not status[len(s)].isalnum()):
            return s
    return None


def load_trace(tree: Tree, errors: list[str]) -> list[Rec]:
    out = []
    for name in tree.names(TRACE_DIR):
        if name in (TEMPLATE, "README.md"):
            continue
        where = f"{TRACE_DIR}/{name}"
        if not name.endswith(".yaml"):
            errors.append(f"{where}: rows are <ID>[-<slug>].yaml")
            continue
        try:
            data = yaml.safe_load(tree.read(where) or "")
        except yaml.YAMLError as exc:
            errors.append(f"{where}: not valid YAML ({exc})")
            continue
        if not isinstance(data, dict) or not TRACE_ID.match(str(data.get("id", ""))):
            errors.append(f"{where}: needs `id: <PREFIX><number>` (e.g. R12)")
            continue
        rid = str(data["id"])
        if not re.match(rf"^{rid}(-[a-z0-9-]+)?\.yaml$", name):
            errors.append(f"{where}: file name must start with its id {rid}")
        unknown = set(data) - {"id", "order", *TRACE_FIELDS}
        empty = [f for f in TRACE_FIELDS if not isinstance(data.get(f), str) or not data[f].strip()]
        if unknown:
            errors.append(f"{where}: unknown fields {sorted(unknown)}")
        if empty:
            errors.append(f"{where}: fill in {', '.join(empty)}")
        elif status_of(data["status"]) is None:
            errors.append(f"{where}: status must start with one of {', '.join(STATUSES)}")
        out.append(Rec(rid, data, name))
    return out


def trace_num(key: str) -> float:
    m = TRACE_ID.match(key)
    return float(m.group(2)) if m else 0.0


def counts_lines(rows: list[Rec]) -> list[str]:
    tally = {s: 0 for s in STATUSES}
    for r in rows:
        s = status_of(str(r.data.get("status", "")))
        if s:
            tally[s] += 1
    return (["| Status | Rows |", "| --- | --- |"] + [f"| {s} | {n} |" for s, n in tally.items()]
            + [f"| **total** | **{len(rows)}** |"])


def sort_key(r: Rec, natural: Callable[[str], float]) -> tuple[float, float, str]:
    order = r.data.get("order")
    return (float(order) if order is not None else natural(r.key), natural(r.key), r.key)


def render_trace(template: str, rows: list[Rec]) -> str:
    out = []
    for line in lines_of(template):
        m = re.fullmatch(r"<!-- traceability\.d:rows ([A-Z]+) -->", line)
        if line == "<!-- traceability.d:counts -->":
            out += counts_lines(rows)
        elif m:
            mine = [r for r in rows if prefix_of(r.key) == m.group(1)]
            for r in sorted(mine, key=lambda r: sort_key(r, trace_num)):
                d = r.data
                out.append(f"| {r.key} | {d['requirement']} | {d['status']} | {d['code']} | {d['test']} |")
        else:
            out.append(line)
    return "\n".join(out) + "\n"


def trace_prefixes(template: str) -> set[str]:
    return set(re.findall(r"<!-- traceability\.d:rows ([A-Z]+) -->", template))


def parse_trace(text: str) -> tuple[str, list[Rec]]:
    out: list[str] = []
    rows: list[Rec] = []
    run: list[tuple[str, float]] = []
    orders: dict[str, float] = {}
    lines = lines_of(strip_notice(text))
    i = 0
    while i < len(lines):
        line = lines[i]
        if line == "| Status | Rows |":
            while i < len(lines) and lines[i].startswith("|"):
                i += 1
            out.append("<!-- traceability.d:counts -->")
            continue
        m = TRACE_ROW.match(line)
        if m:
            cells = m.group(2).split(" | ")
            if len(cells) != 4:
                raise DocsError(f"TRACEABILITY row {m.group(1)} does not have 5 cells")
            if not run:
                out.append(f"<!-- traceability.d:rows {prefix_of(m.group(1))} -->")
            elif prefix_of(m.group(1)) != prefix_of(run[0][0]):
                raise DocsError(f"TRACEABILITY row {m.group(1)} sits in a table of {run[0][0]}'s prefix")
            rows.append(Rec(m.group(1), {"id": m.group(1), **dict(zip(TRACE_FIELDS, cells, strict=True))}))
            run.append((m.group(1), trace_num(m.group(1))))
        else:
            if run:
                orders |= natural_order(run)
                run = []
            out.append(line)
        i += 1
    orders |= natural_order(run)
    for r in rows:
        if r.key in orders:
            r.data["order"] = orders[r.key]
    return "\n".join(out) + "\n", rows


def trace_name(r: Rec, slug: str) -> str:
    return f"{r.key}-{slug}.yaml" if slug else f"{r.key}.yaml"


def trace_renumber(r: Rec, new: str) -> Rec:
    data = {**r.data, "id": new}
    data.pop("order", None)
    return Rec(new, data, r.name)


# ---- BACKLOG

BACKLOG_DIR = "docs/backlog.d"
BACKLOG_NAME = re.compile(r"^(\d+)-([a-z0-9][a-z0-9-]*)\.md$")
BACKLOG_ROW = re.compile(r"^\| (\d+) \| (.*) \|$")
TABLE_FIELDS = ("title", "stage", "size", "status")
ITEM_START = re.compile(r"^(?:### (\d+)\. |- \*\*(\d+))")
ITEMS_MARK = re.compile(r"<!-- backlog\.d:items from=(\d+) -->")


def load_backlog(tree: Tree, errors: list[str]) -> list[Rec]:
    out = []
    for name in tree.names(BACKLOG_DIR):
        if name in (TEMPLATE, "README.md"):
            continue
        where = f"{BACKLOG_DIR}/{name}"
        m = BACKLOG_NAME.match(name)
        if not m:
            errors.append(f"{where}: name must be <number>-<slug>.md (lower-case slug)")
            continue
        try:
            meta, body = split_front_matter(tree.read(where) or "")
        except (DocsError, yaml.YAMLError) as exc:
            errors.append(f"{where}: {exc}")
            continue
        num = meta.get("number")
        if not isinstance(num, int) or str(num) != m.group(1).lstrip("0") or num <= 0:
            errors.append(f"{where}: front matter `number:` must be the number in the file name")
            continue
        unknown = set(meta) - {"number", "rank", "order", *TABLE_FIELDS}
        if unknown:
            errors.append(f"{where}: unknown fields {sorted(unknown)}")
        if meta.get("rank") is not None:
            empty = [f for f in TABLE_FIELDS if not isinstance(meta.get(f), str) or not meta[f].strip()]
            if empty:
                errors.append(f"{where}: a ranked item needs {', '.join(empty)}")
        elif not body.strip():
            errors.append(f"{where}: an item needs a rank (table row) or a detail body")
        out.append(Rec(str(num), {**meta, "body": body.rstrip("\n")}, name))
    return out


def backlog_num(key: str) -> float:
    return float(key) if key.isdigit() else 0.0


def render_backlog(template: str, items: list[Rec]) -> str:
    tlines = lines_of(template)
    froms = sorted(int(m.group(1)) for line in tlines if (m := ITEMS_MARK.fullmatch(line)))
    out: list[str] = []
    for line in tlines:
        mark = ITEMS_MARK.fullmatch(line)
        if line == "<!-- backlog.d:table -->":
            ranked = sorted((r for r in items if r.data.get("rank") is not None),
                            key=lambda r: (float(r.data["rank"]), backlog_num(r.key)))
            out += [f"| {r.key} | " + " | ".join(str(r.data[f]) for f in TABLE_FIELDS) + " |" for r in ranked]
        elif mark:
            lo = int(mark.group(1))
            hi = min((f for f in froms if f > lo), default=math.inf)
            group = [r for r in items if lo <= backlog_num(r.key) < hi and r.data.get("body")]
            for r in sorted(group, key=lambda r: sort_key(r, backlog_num)):
                out += str(r.data["body"]).split("\n")
        else:
            out.append(line)
    return "\n".join(out) + "\n"


def parse_backlog(text: str) -> tuple[str, list[Rec]]:
    lines = lines_of(strip_notice(text))
    out: list[str] = []
    items: dict[str, Rec] = {}
    i = 0
    while i < len(lines) and not BACKLOG_ROW.match(lines[i]):
        out.append(lines[i])
        i += 1
    if i == len(lines):
        raise DocsError("BACKLOG.md has no ranked table")
    out.append("<!-- backlog.d:table -->")
    rank = 0
    while i < len(lines) and (m := BACKLOG_ROW.match(lines[i])):
        cells = m.group(2).split(" | ")
        if len(cells) != 4:
            raise DocsError(f"BACKLOG row {m.group(1)} does not have 5 cells")
        rank += 1
        items[m.group(1)] = Rec(m.group(1), {"number": int(m.group(1)), "rank": rank,
                                             **dict(zip(TABLE_FIELDS, cells, strict=True)), "body": ""})
        i += 1
    # the detail region runs to the next level-2 heading: runs of item blocks between static group headings
    end = next((j for j in range(i, len(lines)) if lines[j].startswith("## ")), len(lines))
    runs: list[list[tuple[str, list[str]]]] = []
    current: list[tuple[str, list[str]]] | None = None
    blanks: list[str] = []  # blank lines between two blocks lead the next block, so the item keeps its spacing
    for line in lines[i:end] + ["## end"]:
        m = ITEM_START.match(line)
        if m:
            if current is None:
                current = []
                runs.append(current)
                out += blanks + [f"<!-- run {len(runs) - 1} -->"]
                blanks = []
            current.append((m.group(1) or m.group(2), blanks + [line]))
        elif line == "":
            blanks.append(line)
            continue
        elif current is not None and not line.startswith("#"):
            current[-1][1].extend(blanks + [line])
        else:
            current = None
            out += blanks + [line]
        blanks = []
    out = out[:-1] + lines[end:]
    for n, run in enumerate(runs):
        order = natural_order([(key, float(key)) for key, _ in run])
        for key, block in run:
            if key in items and items[key].data["body"]:
                raise DocsError(f"BACKLOG item {key} has two detail blocks")
            rec = items.setdefault(key, Rec(key, {"number": int(key), "rank": None, "body": ""}))
            rec.data["body"] = "\n".join(block)
            if key in order:
                rec.data["order"] = order[key]
        out[out.index(f"<!-- run {n} -->")] = f"<!-- backlog.d:items from={min(int(k) for k, _ in run)} -->"
    return "\n".join(out) + "\n", list(items.values())


def backlog_text(r: Rec) -> str:
    meta = {k: v for k, v in r.data.items() if k != "body" and v is not None}
    body = str(r.data.get("body") or "")
    return "---\n" + dump_yaml(meta) + "---\n" + (body + "\n" if body else "")


def backlog_name(r: Rec, slug: str) -> str:
    lead = str(r.data.get("title") or re.sub(r"^(### |- \*\*)\S+\s*", "", str(r.data.get("body") or "")))
    return f"{int(r.key):02d}-{slug or slugify(lead)}.md"


def backlog_renumber(r: Rec, new: str) -> Rec:
    body = re.sub(rf"^(### |- \*\*){r.key}\b", rf"\g<1>{new}", str(r.data.get("body") or ""), count=1)
    data = {**r.data, "number": int(new), "body": body}
    data.pop("order", None)
    return Rec(new, data, r.name)


def trace_text(r: Rec) -> str:
    return dump_yaml({k: r.data[k] for k in ("id", *TRACE_FIELDS, "order") if r.data.get(k) is not None})


SPECS = {
    "traceability": Spec("traceability", "docs/TRACEABILITY.md", TRACE_DIR, TRACE_FIELDS, load_trace, render_trace,
                         parse_trace, trace_text, trace_name, trace_renumber),
    "backlog": Spec("backlog", "docs/BACKLOG.md", BACKLOG_DIR, (*TABLE_FIELDS, "body"), load_backlog, render_backlog,
                    parse_backlog, backlog_text, backlog_name, backlog_renumber),
}
RENDERED = ("HANDOFF.md", "docs/TRACEABILITY.md", "docs/BACKLOG.md")
FRAG_DIRS = (HANDOFF_DIR, TRACE_DIR, BACKLOG_DIR)


def duplicates(recs: list[Rec]) -> dict[str, list[Rec]]:
    seen: dict[str, list[Rec]] = {}
    for r in recs:
        seen.setdefault(r.key, []).append(r)
    return {k: v for k, v in seen.items() if len(v) > 1}


# ---------------------------------------------------------------------------------------------------------- build

def build(tree: Tree) -> dict[str, str]:
    """Rendered path -> text for every doc whose template exists; DocsError lists every problem at once."""
    errors: list[str] = adr_errors(tree)
    out: dict[str, str] = {}
    template = tree.read(f"{HANDOFF_DIR}/{TEMPLATE}")
    if template is not None:
        frags = load_handoff(tree, errors)
        out["HANDOFF.md"] = with_notice(HANDOFF_DIR, render_handoff(template, frags))
    for spec in SPECS.values():
        template = tree.read(f"{spec.dir}/{TEMPLATE}")
        if template is None:
            continue
        recs = spec.load(tree, errors)
        for key, recs_k in sorted(duplicates(recs).items()):
            errors.append(f"{spec.dir}: id {key} is used by {', '.join(str(r.name) for r in recs_k)}; "
                          "run `python scripts/docs_assemble.py fix-ids`")
        if spec.kind == "traceability":
            prefixes = trace_prefixes(template)
            for r in recs:
                p = prefix_of(r.key)
                if p not in prefixes:
                    errors.append(f"{spec.dir}/{r.name}: no table for prefix {p} in {TEMPLATE} "
                                  f"(add `<!-- traceability.d:rows {p} -->`)")
        out[spec.rendered] = with_notice(spec.dir, spec.render(template, recs))
    if errors:
        raise DocsError("\n".join(errors))
    return out


def cmd_render(root: Path) -> int:
    for rel, text in build(FsTree(root)).items():
        path = root / rel
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            print(f"rendered {rel}")
    return 0


def cmd_check(root: Path) -> int:
    try:
        built = build(FsTree(root))
    except DocsError as exc:
        print(exc, file=sys.stderr)
        return 1
    stale = 0
    for rel, text in built.items():
        have = FsTree(root).read(rel) or ""
        if have != text:
            stale += 1
            print(f"{rel} differs from its fragments: {HINT}.", file=sys.stderr)
            diff = difflib.unified_diff(lines_of(text), lines_of(have), "fragments", rel, lineterm="", n=1)
            print("\n".join(list(diff)[:40]), file=sys.stderr)
    return 1 if stale else 0


# -------------------------------------------------------------------------------------------------------- new ids

def next_number(keys: list[str], natural: Callable[[str], float]) -> int:
    """Always one past the highest id ever in use, so a retired id is never handed out again."""
    return int(max((natural(k) for k in keys), default=0)) + 1


def next_free(spec: Spec, taken: set[str], like: str) -> str:
    if spec.kind == "traceability":
        prefix = prefix_of(like)
        return f"{prefix}{next_number([k for k in taken if prefix_of(k) == prefix], trace_num)}"
    return str(next_number(list(taken), backlog_num))


def cmd_new_handoff(root: Path, slug: str, section: str, today: dt.date | None = None) -> Path:
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", slug):
        raise DocsError("slug: lower-case letters, digits and hyphens")
    path = root / HANDOFF_DIR / f"{(today or dt.date.today()).isoformat()}-{slug}.md"
    if path.exists():
        raise DocsError(f"{path} exists")
    head = "---\nsection: next\n---\n" if section == "next" else ""
    path.write_text(f"{head}- {STUB}\n", encoding="utf-8")
    return path


def cmd_new_row(root: Path, prefix: str, slug: str, fields: dict[str, str] | None = None) -> Path:
    spec, tree = SPECS["traceability"], FsTree(root)
    if prefix not in trace_prefixes(tree.read(f"{TRACE_DIR}/{TEMPLATE}") or ""):
        raise DocsError(f"no table for prefix {prefix} in {TRACE_DIR}/{TEMPLATE}")
    keys = [r.key for r in spec.load(tree, []) if prefix_of(r.key) == prefix]
    rid = f"{prefix}{next_number(keys, trace_num)}"
    rec = Rec(rid, {"id": rid, **{f: (fields or {}).get(f, "") for f in TRACE_FIELDS}})
    path = root / TRACE_DIR / trace_name(rec, slug)
    path.write_text(trace_text(rec), encoding="utf-8")
    return path


def cmd_new_item(root: Path, slug: str, title: str, stage: str = "", size: str = "", status: str = "proposed",
                 detail_only: bool = False) -> Path:
    spec, tree = SPECS["backlog"], FsTree(root)
    recs = spec.load(tree, [])
    num = next_number([r.key for r in recs], backlog_num)
    ranks = [float(r.data["rank"]) for r in recs if r.data.get("rank") is not None]
    data: dict[str, Any] = {"number": num, "rank": None if detail_only else int(max(ranks, default=0)) + 1,
                            "title": title, "stage": stage, "size": size, "status": status,
                            "body": f"- **{num}. {title}.** Value: {STUB}. Acceptance: {STUB}."}
    rec = Rec(str(num), data)
    path = root / BACKLOG_DIR / backlog_name(rec, slug)
    path.write_text(backlog_text(rec), encoding="utf-8")
    return path


# -------------------------------------------------------------------------------------------------------- fix-ids

def landed_at(root: Path, rel: str) -> float:
    """When the file first appeared on this branch's first-parent line (untracked or only staged: never)."""
    r = git(root, "log", "--first-parent", "--diff-filter=A", "--format=%ct", "--", rel, check=False)
    stamps = [int(s) for s in r.stdout.split()] if r.returncode == 0 else []
    return float(stamps[-1]) if stamps else math.inf


def write_rec(root: Path, spec: Spec, rec: Rec, slug: str = "") -> str:
    name = rec.name or spec.file_name(rec, slug)
    (root / spec.dir / name).write_text(spec.file_text(rec), encoding="utf-8")
    return name


def cmd_fix_ids(root: Path) -> list[str]:
    notes: list[str] = []
    tree = FsTree(root)
    for spec in SPECS.values():
        recs = spec.load(tree, [])
        taken = {r.key for r in recs}
        for key, clash in sorted(duplicates(recs).items()):
            clash.sort(key=lambda r: (landed_at(root, f"{spec.dir}/{r.name}"), str(r.name)))
            for r in clash[1:]:
                new = next_free(spec, taken, key)
                slug = re.sub(rf"^0*{key}-?", "", Path(str(r.name)).stem)
                taken.add(new)
                moved = spec.renumber(r, new)
                moved.name = spec.file_name(moved, slug)
                (root / spec.dir / str(r.name)).unlink()
                write_rec(root, spec, moved)
                notes.append(f"{spec.dir}: {key} ({r.name}) -> {new} ({moved.name}); kept {key} for {clash[0].name}. "
                             f"Check the branch's other fragments for references to {key}.")
    return notes


# --------------------------------------------------------------------------------------------------------- absorb

def merge_text(root: Path, current: str, base: str, other: str) -> tuple[str, bool]:
    """git merge-file: (merged text, clean)."""
    with tempfile.TemporaryDirectory() as tmp:
        paths = []
        for name, text in (("current", current), ("base", base), ("branch", other)):
            p = Path(tmp) / name
            p.write_text(text, encoding="utf-8")
            paths.append(str(p))
        r = subprocess.run(["git", "merge-file", "-p", "-L", "current", "-L", "base", "-L", "branch", *paths],
                           cwd=root, capture_output=True, text=True, encoding="utf-8")
    if r.returncode < 0:
        raise DocsError(f"git merge-file failed: {r.stderr}")
    return r.stdout, r.returncode == 0


@dataclass
class Absorbed:
    notes: list[str] = field(default_factory=list)
    conflicts: list[str] = field(default_factory=list)


def branch_slug(root: Path, ref: str) -> str:
    name = git(root, "rev-parse", "--abbrev-ref", ref, check=False).stdout.strip() or ref
    return slugify(name.replace("/", "-"), words=8)


def absorb_template(root: Path, rel: str, base_sk: str, branch_sk: str, res: Absorbed) -> None:
    if base_sk == branch_sk:
        return
    path = root / rel
    merged, clean = merge_text(root, path.read_text(encoding="utf-8"), base_sk, branch_sk)
    path.write_text(merged, encoding="utf-8")
    (res.notes if clean else res.conflicts).append(
        f"{rel}: the branch's edits to the static text " + ("applied" if clean else "conflict; resolve the markers"))


def absorb_handoff(root: Path, base: str, branch: str, slug: str, date: str, res: Absorbed) -> None:
    """New top-level bullets become fragments; every other edit is merged into the template."""
    b, t = lines_of(base), lines_of(branch)
    heads = {s: next((i for i, line in enumerate(b) if line.startswith(h)), len(b)) for s, h in HANDOFF_SECTIONS.items()}
    end_next = next((i for i, line in enumerate(b) if line.startswith("## ") and i > heads["next"]), len(b))
    added: dict[str, list[str]] = {"status": [], "next": []}
    edited: list[str] = []
    for op, i1, i2, j1, j2 in difflib.SequenceMatcher(None, b, t, autojunk=False).get_opcodes():
        block = t[j1:j2]
        at = b[i1] if i1 < len(b) else ""
        boundary = at == "" or at.startswith(("- ", "## ")) or bool(re.match(r"\d+\. ", at))
        section = "status" if heads["status"] < i1 <= heads["next"] else "next" if heads["next"] < i1 <= end_next else ""
        if op == "insert" and block[0].startswith("- ") and boundary and section and all(block):
            added[section] += block
            edited += b[i1:i2]
        else:
            edited += t[j1:j2] if op != "equal" else b[i1:i2]
    rel = f"{HANDOFF_DIR}/{TEMPLATE}"
    absorb_template(root, rel, handoff_skeleton(base), handoff_skeleton("\n".join(edited) + "\n"), res)
    for section, block in added.items():
        if not block:
            continue
        name = f"{date}-{slug}{'-next' if section == 'next' else ''}.md"
        n = 2
        while (root / HANDOFF_DIR / name).exists():
            name = f"{date}-{slug}{'-next' if section == 'next' else ''}-{n}.md"
            n += 1
        head = "---\nsection: next\n---\n" if section == "next" else ""
        (root / HANDOFF_DIR / name).write_text(head + "\n".join(block) + "\n", encoding="utf-8")
        res.notes.append(f"{HANDOFF_DIR}/{name}: {len(block)} new HANDOFF line(s)")


def absorb_structured(root: Path, spec: Spec, base: str, branch: str, slug: str, res: Absorbed) -> None:
    base_sk, base_recs = spec.parse(base)
    branch_sk, branch_recs = spec.parse(branch)
    absorb_template(root, f"{spec.dir}/{TEMPLATE}", base_sk, branch_sk, res)
    cur = {r.key: r for r in spec.load(FsTree(root), [])}
    b = {r.key: r for r in base_recs}
    taken = set(cur) | {r.key for r in branch_recs}
    fields = spec.merge_fields
    if spec.kind == "backlog":
        before, after = ranked_keys(base_recs), ranked_keys(branch_recs)
        if [k for k in before if k in after] != [k for k in after if k in before]:
            res.notes.append(f"{spec.rendered}: the branch re-ranked items; ranks were not absorbed, re-rank by hand")
    for t in branch_recs:
        base_rec, now = b.get(t.key), cur.get(t.key)
        if base_rec is None:
            if now is not None and all(now.data.get(f) == t.data.get(f) for f in fields):
                continue
            new = t
            if now is not None:  # another lane took the id first
                key = next_free(spec, taken, t.key)
                taken.add(key)
                new = spec.renumber(t, key)
                res.notes.append(f"{spec.rendered}: the branch's new {t.key} is taken; absorbed as {key}. "
                                 f"Check the branch's HANDOFF text for references to {t.key}.")
            new.data.pop("order", None)
            if spec.kind == "backlog" and t.data.get("rank") is not None:
                new.data["rank"] = absorbed_rank(t, branch_recs, cur)
            name = write_rec(root, spec, Rec(new.key, new.data), slug if spec.kind == "traceability" else "")
            res.notes.append(f"{spec.dir}/{name}: new from the branch")
            continue
        if all(base_rec.data.get(f) == t.data.get(f) for f in fields):
            continue
        if now is None:
            res.conflicts.append(f"{spec.rendered}: the branch edited {t.key}, which no longer exists here")
            continue
        merged = dict(now.data)
        for f in fields:
            bv, tv, cv = base_rec.data.get(f), t.data.get(f), now.data.get(f)
            if tv == bv or tv == cv:
                continue
            if cv == bv:
                merged[f] = tv
            elif f == "body":
                text, clean = merge_text(root, f"{cv}\n", f"{bv}\n", f"{tv}\n")
                merged[f] = text.rstrip("\n")
                if not clean:
                    res.conflicts.append(f"{spec.dir}/{now.name}: body edited on both sides; resolve the markers")
            else:
                res.conflicts.append(f"{spec.dir}/{now.name}: `{f}` edited on both sides; kept the current value, "
                                     f"the absorbed branch has: {tv}")
        if merged != now.data:
            write_rec(root, spec, Rec(now.key, merged, now.name))
            res.notes.append(f"{spec.dir}/{now.name}: the branch's edit applied")
    for key, base_rec in b.items():
        now = cur.get(key)
        if key not in {r.key for r in branch_recs} and now is not None:
            if all(now.data.get(f) == base_rec.data.get(f) for f in fields):
                (root / spec.dir / str(now.name)).unlink()
                res.notes.append(f"{spec.dir}/{now.name}: deleted by the branch")
            else:
                res.conflicts.append(f"{spec.dir}/{now.name}: deleted by the branch but edited here; kept")


def ranked_keys(recs: list[Rec]) -> list[str]:
    return [r.key for r in sorted((r for r in recs if r.data.get("rank") is not None),
                                  key=lambda r: float(r.data["rank"]))]


def absorbed_rank(t: Rec, branch_recs: list[Rec], cur: dict[str, Rec]) -> float:
    """Just below the item the branch ranked it under (by the current ranks), else above the first."""
    ranked = sorted((r for r in branch_recs if r.data.get("rank") is not None), key=lambda r: float(r.data["rank"]))
    above = [r.key for r in ranked[:ranked.index(t)] if r.key in cur and cur[r.key].data.get("rank") is not None]
    ranks = sorted(float(r.data["rank"]) for r in cur.values() if r.data.get("rank") is not None)
    if not above:
        return (ranks[0] - 1) if ranks else 1
    anchor = float(cur[above[-1]].data["rank"])
    after = [x for x in ranks if x > anchor]
    return (anchor + after[0]) / 2 if after else anchor + 1


def cmd_absorb(root: Path, ref: str, base: str | None = None) -> Absorbed:
    res = Absorbed()
    tip = git(root, "rev-parse", "--verify", ref).stdout.strip()
    base = base or git(root, "merge-base", "HEAD", tip).stdout.strip()
    then, there = GitTree(root, base), GitTree(root, tip)
    slug = branch_slug(root, ref)
    date = git(root, "log", "-1", "--format=%cs", tip).stdout.strip()
    jobs = [("HANDOFF.md", HANDOFF_DIR, None)] + [(s.rendered, s.dir, s) for s in SPECS.values()]
    for rendered, frag_dir, spec in jobs:
        if there.read(f"{frag_dir}/{TEMPLATE}") is not None:
            continue  # new-style branch: its fragments merge as files
        old, new = then.read(rendered), there.read(rendered)
        if old is None or new is None or old == new:
            continue
        if spec is None:
            absorb_handoff(root, old, new, slug, date, res)
        else:
            absorb_structured(root, spec, old, new, slug, res)
    return res


# ---------------------------------------------------------------------------------------------------------- merge

def cmd_merge(root: Path, ref: str) -> int:
    if git(root, "status", "--porcelain", "--untracked-files=no").stdout.strip():
        raise DocsError("the work tree has uncommitted changes; commit them first")
    tip = git(root, "rev-parse", "--verify", ref).stdout.strip()
    there = GitTree(root, tip)
    if any(there.read(f"{d}/{TEMPLATE}") is not None for d in FRAG_DIRS):
        built = build(there)
        stale = [rel for rel, text in built.items() if there.read(rel) != text]
        if stale:
            raise DocsError(f"{ref} edited {', '.join(stale)} by hand (they differ from its fragments); move the text "
                            "into fragments on that branch first, or nothing it added there would survive")
    base = git(root, "merge-base", "HEAD", tip).stdout.strip()
    r = git(root, "merge", "--no-ff", "--no-commit", tip, check=False)
    if git(root, "rev-parse", "-q", "--verify", "MERGE_HEAD", check=False).returncode != 0:
        print(r.stdout.strip() or r.stderr.strip())
        return 0 if r.returncode == 0 else 1
    conflicted = set(git(root, "diff", "--name-only", "--diff-filter=U").stdout.split())
    for rel in conflicted & set(RENDERED):
        git(root, "checkout", "--ours", "--", rel)
    res = cmd_absorb(root, tip, base)
    notes = res.notes + cmd_fix_ids(root)
    cmd_render(root)
    git(root, "add", "-A", "--", *RENDERED, *FRAG_DIRS)
    for note in notes:
        print(note)
    left = sorted(set(git(root, "diff", "--name-only", "--diff-filter=U").stdout.split()))
    if left or res.conflicts:
        print("merge left open (finish with `git commit` once resolved):", file=sys.stderr)
        for item in res.conflicts + [f"{rel}: conflict" for rel in left]:
            print(f"  {item}", file=sys.stderr)
        return 1
    git(root, "commit", "--no-edit")
    print(f"merged {ref}")
    return 0


