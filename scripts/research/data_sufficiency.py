"""Render the data-sufficiency contract (goldbot/research/data_sufficiency.py) from config/data/sufficiency.yaml:
docs/data/sufficiency.md (the table), docs/data/sufficiency_status.json (machine-readable certificates) and one
health line per cell on stdout.

    python scripts/research/data_sufficiency.py            # write both files, print the health lines
    python scripts/research/data_sufficiency.py --check    # exit 1 when the rendered files are stale
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

from goldbot.research import data_sufficiency as D

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "config" / "data" / "sufficiency.yaml"
MD = ROOT / "docs" / "data" / "sufficiency.md"
JS = ROOT / "docs" / "data" / "sufficiency_status.json"


def _gap(item: str, d: dict[str, Any], blocks: bool = True) -> D.Gap:
    return D.Gap(item=item, gap=d["gap"], plan=d["plan"], owner=str(d["owner"]), due=str(d["due"]), blocks=blocks)


def certificates(cfg: dict[str, Any]) -> list[D.Certificate]:
    req0 = cfg["requirement"]
    out = []
    for unit, u in cfg["units"].items():
        for i, tf in enumerate(cfg["tfs"]):
            req = D.Requirement(cell=f"{unit}/{tf}", unit=unit, tf=tf, inputs=int(req0["inputs"]),
                                keep_share=float(req0["keep_share"]), objective=req0["objective"],
                                label_templates=req0["label_templates"])
            learn = None if u["learn"] is None else int(u["learn"][i])
            judge = None if u["judge"] is None else int(u["judge"][i])
            gaps = [_gap(k, cfg["items"][k]) for k in [*cfg.get("tf_items", {}).get(tf, []), *u["items"]]]
            if learn is not None and learn < req.n_train():
                gaps.append(D.Gap(item="POOL", gap=f"learn n_eff {learn:,} < {req.n_train():,} for a "
                                  f"{req.inputs}-input block (max {learn // D.RILEY_PER_PARAM} inputs)",
                                  plan="deliver the pooled cross-class set at this tf (card 2.2 pooling, "
                                       "rho_inst 0.5) and the per-cell input cap to the card",
                                  owner="data-engineer + ml-researcher", due="2026-12-16"))
            if judge is not None and judge < req.n_judge():
                gaps.append(D.Gap(item="POWER", gap=f"judge n_eff {judge:,} < {req.n_judge():,} at keep "
                                  f"{req.keep_share}", plan="judge at a lower label-blind keep share (A22 row) or "
                                  "pooled; the 2003-09 test_old years once D-1 grades them",
                                  owner="quant-reviewer + data-engineer", due="2026-12-11"))
            out.append(D.certify(req, learn, judge, gaps))
    return out


def render(cfg: dict[str, Any], certs: list[D.Certificate]) -> str:
    def n(x: int | None) -> str:
        return "-" if x is None else f"{x:,}"
    lines = [
        "# Data sufficiency (generated)", "",
        f"Generated by `scripts/research/data_sufficiency.py` from `config/data/sufficiency.yaml` (as of {cfg['as_of']}). "
        "Do not edit by hand. Owner: data-engineer (owner directive 2026-11-25: the data team provides the necessary "
        "and sufficient data for models).", "",
        "Requirement (ML side, sr-v3 card rev 2): learn n_eff >= 430 per input (Riley, continuous outcome, shrinkage "
        f">= 0.9) for a {cfg['requirement']['inputs']}-input block; judge n_eff >= the A22 power row at keep share "
        f"{cfg['requirement']['keep_share']}. Supply: the card's n_eff method (2.2) until the dense label factory "
        "(D-5) measures each cell. A cell is SUFFICIENT only when the numbers meet the requirement AND no blocking "
        "data item is open; `projected` is the verdict on the numbers alone. SHORT is never a conclusion: every SHORT "
        "cell names its gap, plan, owner and date.", "",
        "## Cells", "",
        "| Cell | Verdict | Projected | Learn n_eff / need | Max inputs | Judge n_eff / need | First open item (due) |",
        "|---|---|---|---|---|---|---|",
    ]
    for c in certs:
        g = c.gaps[0] if c.gaps else None
        first = f"{g.item}: {g.gap} ({g.due})" if g else ""
        lines.append(f"| {c.cell} | {c.verdict} | {c.projected} | {n(c.n_eff_learn)} / {c.need_train:,} | "
                     f"{n(c.max_inputs)} | {n(c.n_eff_judge)} / {c.need_judge:,} | {first} |")
    lines += ["", "## Data items (sr-v3 card 9a) and date risk", "",
              "| Item | Gap | Plan | Owner | Due | Status | Risk |", "|---|---|---|---|---|---|---|"]
    for k, d in {**cfg["items"], **cfg["other_items"]}.items():
        lines.append(f"| {k} | {d['gap']} | {d['plan']} | {d['owner']} | {d['due']} | {d['status']} | {d['risk']} |")
    lines += ["", "## Units", ""]
    for unit, u in cfg["units"].items():
        lines.append(f"- `{unit}`: {u['label']}; learn {u['windows']['learn']}, judge {u['windows']['judge']}.")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    cfg = yaml.safe_load(SRC.read_text())
    certs = certificates(cfg)
    md = render(cfg, certs)
    js = json.dumps({"as_of": cfg["as_of"], "cells": [c.model_dump(mode="json") for c in certs]}, indent=1) + "\n"
    if a.check:
        stale = [p for p, body in ((MD, md), (JS, js)) if not p.exists() or p.read_text() != body]
        if stale:
            print("stale: " + ", ".join(str(p.relative_to(ROOT)) for p in stale), file=sys.stderr)
            return 1
        return 0
    MD.parent.mkdir(parents=True, exist_ok=True)
    MD.write_text(md)
    JS.write_text(js)
    for c in certs:
        print(c.health_line())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
