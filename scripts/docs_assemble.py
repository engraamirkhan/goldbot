#!/usr/bin/env python3
"""Render HANDOFF.md, docs/TRACEABILITY.md and docs/BACKLOG.md from one-file-per-change fragments.

Why (docs/process/speed-up-review.md items 1-2, ADR 0012): 69% of merges needed hand resolution, mostly in these
three files, because every parallel lane appended to the same lines and took the same row ids and counts. A new
file never conflicts, so each change now adds a fragment and the rendered files are generated:

* HANDOFF.md      = docs/handoff.d/_template.md + docs/handoff.d/<YYYY-MM-DD>-<slug>.md, newest first, at the top of
                    "Where things are" (or of "Next steps" with `section: next` in the fragment's front matter).
* TRACEABILITY.md = docs/traceability.d/_template.md + one YAML per row (`<ID>.yaml` or `<ID>-<slug>.yaml`; the
                    `id:` field is the id). The counts table is computed from the rows.
* BACKLOG.md      = docs/backlog.d/_template.md + docs/backlog.d/<NN>-<slug>.md (front matter: number, rank, table
                    cells; body: the item's detail block). The ranked table is sorted by `rank`.

Never edit the rendered files: `check` (pre-commit hook and CI) fails when they differ from the fragments.

Commands (all take --root, default the repo):
  render                         write the three files from the fragments (the default command)
  check                          exit 1 when a rendered file is stale or two fragments share an id
  new-handoff SLUG [--next]      create docs/handoff.d/<today>-<SLUG>.md
  new-row PREFIX --slug S        create the next free TRACEABILITY row id for PREFIX (e.g. R) as a YAML stub
  new-item --slug S --title T    create the next free BACKLOG number, ranked last
  fix-ids                        renumber clashing ids: the fragment that landed first on this branch keeps its id
  absorb BRANCH                  turn an old-style branch's edits to the rendered files into fragments
  merge BRANCH                   git merge --no-commit + absorb + fix-ids + render + commit, in one go
  migrate                        one-off split of the old rendered files into fragments (kept: absorb parses the
                                 old format with the same code, and the lossless test replays it)
  install-merge-driver           register the `goldbot-docs` git merge driver in this repo's git config, so a plain
                                 merge, rebase or cherry-pick re-renders the rendered docs instead of conflicting
  merge-driver %O %A %B %P ...   the driver itself (git calls it; `.gitattributes` routes the rendered docs to it)
  new-adr --slug S --title T     reserve the next ADR number under a lock in the git common dir and write
                                 docs/decisions/NNNN-S.md (`--number N` claims a number in reserved.yaml)

`check` also fails on two ADR files with one number.

Standalone on purpose (stdlib + PyYAML, no goldbot import): the pre-commit hook runs it in its own environment.
"""
