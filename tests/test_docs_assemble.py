"""scripts/docs_assemble.py: HANDOFF, TRACEABILITY and BACKLOG rendered from one-file-per-change fragments.

Design rule (docs/process/speed-up-review.md items 1-2, ADR 0012): parallel lanes add new files only, so their
merges never conflict on the shared docs; the rendered files are generated, stale ones fail the pre-commit check,
clashing ids are caught and renumbered mechanically, and an old-style branch is absorbed in one command.
"""
from __future__ import annotations

import importlib.util
import os
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location("docs_assemble", ROOT / "scripts" / "docs_assemble.py")
assert _spec and _spec.loader
da = importlib.util.module_from_spec(_spec)
sys.modules["docs_assemble"] = da
_spec.loader.exec_module(da)

