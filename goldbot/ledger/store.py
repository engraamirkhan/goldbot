"""The program ledger store: append-only rows in state/program.db (docs: goldbot/db/migrations.py PROGRAM).

Design rules:
* "A row is never updated or deleted": a changed fact is a new version of the same key that supersedes the old one
  (the only UPDATE the database allows sets the old row's `superseded_by_id` once, from NULL). Appending content
  identical to the key's latest version is a no-op that returns the existing id (imports are idempotent).
* "Secrets and account identifiers never enter the ledger": every text that is stored is scanned first
  (goldbot/ledger/scan.py); a hit, or a scanner that fails, refuses the add and writes nothing (fail closed).
* "Export writes public rows only": docs/ledger/*.md hold privacy='public' rows, never `owner_notes`, and are scanned
  again before anything is written."""
from __future__ import annotations

import hashlib
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from goldbot.db import Database, StateDbError
from goldbot.db.connection import now_ns
from goldbot.ledger import scan
from goldbot.ledger.models import MAX_BLOB_BYTES, TABLE_FIELDS, NewEntry

EXPORT_HEADER = ("<!-- generated by `python -m goldbot.ops.run ledger export` from state/program.db (public rows "
                 "only); do not edit -->")


class LedgerRefused(StateDbError):
    """An entry was refused (secret or identifier found, scanner failed, or a rule broken). Nothing was written."""


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _check_clean(texts: Iterable[str]) -> None:
    try:
        hits = sorted({h for t in texts for h in scan.scan(t)})
    except scan.ScanError as exc:
        raise LedgerRefused(f"refused: {exc}") from None
    if hits:
        raise LedgerRefused(f"refused: looks like a secret or account identifier ({', '.join(hits)}); "
                            "credentials live in the keyring, never in the ledger")


class Ledger:
    def __init__(self, db: Database):
        self.db = db
        self._check_triggers()

    def _check_triggers(self) -> None:
        """Refuse to open a program.db that lacks any append-only trigger: without them nothing stops an UPDATE."""
        from goldbot.db.migrations import ledger_trigger_names
        with self.db.read() as c:
            have = {r[0] for r in c.execute("SELECT name FROM sqlite_master WHERE type = 'trigger'")}
        missing = sorted(set(ledger_trigger_names()) - have)
        if missing:
            raise LedgerRefused(f"program.db is missing append-only triggers ({', '.join(missing)}); "
                                "restore it from a backup")

    @classmethod
    def open(cls, state_dir: str | Path, *, migrate: bool = True) -> Ledger:
        return cls(Database.open(state_dir, "program", migrate=migrate))

    # ------------------------------------------------------------------ write
    def add(self, e: NewEntry) -> int:
        """Append `e` (a new version when its key exists); returns the row id."""
        privacy = e.resolved_privacy
        if e.table == "owner_notes" and privacy != "private":
            raise LedgerRefused("refused: owner_notes are private")
        blob = e.blob
        texts = [e.key, e.body, e.source, *e.fields.values()]
        if blob is not None:
            texts.append(blob.decode("utf-8", errors="replace"))
        _check_clean(texts)
        extra: dict[str, Any] = dict(e.fields)
        if blob is not None:
            extra["size"] = len(blob)
            extra["blob"] = blob if len(blob) <= MAX_BLOB_BYTES else None
        sha = _sha256(blob if blob is not None else e.body.encode("utf-8"))
        with self.db.write() as c:
            prev = c.execute(f"SELECT * FROM {e.table} WHERE key = ? AND superseded_by_id IS NULL", (e.key,))
            cols = [d[0] for d in prev.description]
            row = prev.fetchone()
            latest = dict(zip(cols, row, strict=True)) if row else None
            if latest and latest["sha256"] == sha and latest["privacy"] == privacy and all(
                    latest[k] == v for k, v in extra.items() if k != "blob") and latest["body"] == e.body:
                return int(latest["id"])
            values: dict[str, Any] = {"key": e.key, "version": (latest["version"] + 1) if latest else 1,
                                      "body": e.body, "sha256": sha, "created_ns": now_ns(), "source": e.source,
                                      "supersedes_id": latest["id"] if latest else None, "privacy": privacy, **extra}
            names = ", ".join(values)
            rid = c.execute(f"INSERT INTO {e.table} ({names}) VALUES ({', '.join('?' * len(values))})",
                            tuple(values.values())).lastrowid
            assert rid is not None
            if latest:
                c.execute(f"UPDATE {e.table} SET superseded_by_id = ? WHERE id = ?", (rid, latest["id"]))
            return rid

    # ------------------------------------------------------------------ read
    def _rows(self, sql: str, args: tuple[Any, ...] = ()) -> list[dict[str, Any]]:
        with self.db.read() as c:
            cur = c.execute(sql, args)
            cols = [d[0] for d in cur.description]
            return [dict(zip(cols, r, strict=True)) for r in cur.fetchall()]

    def get(self, table: str, row_id: int) -> dict[str, Any]:
        self._known(table)
        rows = self._rows(f"SELECT * FROM {table} WHERE id = ?", (row_id,))
        if not rows:
            raise KeyError(f"{table} has no row {row_id}")
        return rows[0]

    def query(self, table: str, *, text: str | None = None, include_private: bool = False,
              history: bool = False, limit: int = 200) -> list[dict[str, Any]]:
        """Newest first. Only the latest version of each key unless `history`; private rows only when asked for."""
        self._known(table)
        where, args = ["1=1"], []
        if not history:
            where.append("superseded_by_id IS NULL")
        if not include_private:
            where.append("privacy = 'public'")
        if text:
            where.append("(key LIKE ? OR body LIKE ?)")
            args += [f"%{text}%", f"%{text}%"]
        rows = self._rows(f"SELECT * FROM {table} WHERE {' AND '.join(where)} ORDER BY id DESC LIMIT ?",
                          (*args, limit))
        for r in rows:
            r.pop("blob", None)
        return rows

    def latest_resume(self) -> str | None:
        rows = self._rows("SELECT body FROM resume_snapshots ORDER BY id DESC LIMIT 1")
        return str(rows[0]["body"]) if rows else None

    @staticmethod
    def _known(table: str) -> None:
        if table not in TABLE_FIELDS:
            raise ValueError(f"unknown ledger table {table!r}; one of {sorted(TABLE_FIELDS)}")

    # ------------------------------------------------------------------ export
    def export(self, out_dir: str | Path) -> list[Path]:
        """Write one generated markdown file per table with public rows (never `owner_notes`). Every text is scanned
        again first; one dirty row refuses the whole export and nothing is written."""
        pages: dict[str, str] = {}
        for table in TABLE_FIELDS:
            if table == "owner_notes":
                continue
            rows = self._rows(f"SELECT * FROM {table} WHERE privacy = 'public' ORDER BY id")
            if not rows:
                continue
            parts = [EXPORT_HEADER, f"# {table}"]
            for r in rows:
                state = f"superseded by #{r['superseded_by_id']}" if r["superseded_by_id"] else "current"
                parts.append(f"## {r['key']} v{r['version']} (#{r['id']}, {state})")
                own = [f"- {k}: {r[k]}" for k in TABLE_FIELDS[table] if k in r]
                if table == "artifacts":
                    own.append(f"- size: {r['size']}; sha256: {r['sha256']}")
                parts += [f"- source: {r['source']}; recorded_ns: {r['created_ns']}", *own, "", r["body"].rstrip(), ""]
            pages[table] = "\n".join(parts) + "\n"
        _check_clean(pages.values())
        out = Path(out_dir)
        out.mkdir(parents=True, exist_ok=True)
        (out / "owner_notes.md").unlink(missing_ok=True)       # never present, even from an older export
        written = []
        for table, page in pages.items():
            p = out / f"{table}.md"
            p.write_text(page, encoding="utf-8")
            written.append(p)
        return written


__all__ = ["Ledger", "LedgerRefused", "EXPORT_HEADER"]
